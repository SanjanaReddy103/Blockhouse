    "import pandas as pd\n",
    "import numpy as np\n",
    "import json\n",
    "from itertools import product\n",
    "\n",
    "ORDER_SIZE = 5000\n",
    "CHUNK = 100\n",
    "\n",
    "# Data structure for allocator\n",
    "def create_venue_list(snapshot):\n",
    "    venues = []\n",
    "    for venue, row in snapshot.iterrows():\n",
    "        venues.append({\n",
    "            'venue': venue,\n",
    "            'ask': row['ask_px_00'],\n",
    "            'ask_size': row['ask_sz_00'],\n",
    "            'fee': 0.0,\n",
    "            'rebate': 0.0\n",
    "        })\n",
    "    return venues\n",
    "\n",
    "def compute_cost(split, venues, order_size, lambda_over, lambda_under, theta_queue):\n",
    "    executed = 0\n",
    "    cash_spent = 0\n",
    "    for i in range(len(venues)):\n",
    "        exe = min(split[i], venues[i]['ask_size'])\n",
    "        executed += exe\n",
    "        cash_spent += exe * (venues[i]['ask'] + venues[i]['fee'])\n",
    "        maker_rebate = max(split[i] - exe, 0) * venues[i]['rebate']\n",
    "        cash_spent -= maker_rebate\n",
    "\n",
    "    underfill = max(order_size - executed, 0)\n",
    "    overfill = max(executed - order_size, 0)\n",
    "    risk_penalty = theta_queue * (underfill + overfill)\n",
    "    cost_penalty = lambda_under * underfill + lambda_over * overfill\n",
    "    return cash_spent + risk_penalty + cost_penalty\n",
    "\n",
    "def allocator(snapshot, lambda_over, lambda_under, theta_queue, remaining_qty):\n",
    "    venues = create_venue_list(snapshot)\n",
    "    splits = [[]]\n",
    "    for v in range(len(venues)):\n",
    "        new_splits = []\n",
    "        for alloc in splits:\n",
    "            used = sum(alloc)\n",
    "            max_v = min(remaining_qty - used, venues[v]['ask_size'])\n",
    "            for q in range(0, int(max_v) + 1, CHUNK):\n",
    "                new_splits.append(alloc + [q])\n",
    "        splits = new_splits\n",
    "\n",
    "    best_cost = float('inf')\n",
    "    best_split = [0] * len(venues)\n",
    "    for alloc in splits:\n",
    "        if sum(alloc) != remaining_qty:\n",
    "            continue\n",
    "        cost = compute_cost(alloc, venues, remaining_qty, lambda_over, lambda_under, theta_queue)\n",
    "        if cost < best_cost:\n",
    "            best_cost = cost\n",
    "            best_split = alloc\n",
    "    return {venue['venue']: qty for venue, qty in zip(venues, best_split)}\n",
    "\n",
    "def run_backtest(df, strategy_func, params=None):\n",
    "    total_cost = 0\n",
    "    total_shares = 0\n",
    "    remaining_qty = ORDER_SIZE\n",
    "\n",
    "    for ts in df['ts_event'].unique():\n",
    "        if remaining_qty <= 0:\n",
    "            break\n",
    "        snapshot = df[df['ts_event'] == ts].set_index('publisher_id')\n",
    "        market_data = {\n",
    "            venue: {'ask_px': row['ask_px_00'], 'ask_sz': row['ask_sz_00']}\n",
    "            for venue, row in snapshot.iterrows()\n",
    "        }\n",
    "\n",
    "        if params:\n",
    "            allocations = strategy_func(snapshot, *params, remaining_qty)\n",
    "        else:\n",
    "            allocations = strategy_func(market_data, remaining_qty)\n",
    "\n",
    "        for venue, shares in allocations.items():\n",
    "            px = market_data[venue]['ask_px']\n",
    "            sz = market_data[venue]['ask_sz']\n",
    "            executed = min(shares, sz, remaining_qty)\n",
    "            if executed > 0:\n",
    "                total_cost += executed * px\n",
    "                total_shares += executed\n",
    "                remaining_qty -= executed\n",
    "\n",
    "    avg_price = total_cost / total_shares if total_shares > 0 else 0\n",
    "    return total_cost, avg_price\n",
    "\n",
    "def best_ask_strategy(market_data, remaining_qty):\n",
    "    sorted_venues = sorted(market_data.items(), key=lambda x: x[1]['ask_px'])\n",
    "    allocations = {venue: 0 for venue, _ in sorted_venues}\n",
    "    qty_left = remaining_qty\n",
    "    for venue, data in sorted_venues:\n",
    "        if qty_left <= 0:\n",
    "            break\n",
    "        executable = min(qty_left, data['ask_sz'])\n",
    "        allocations[venue] = executable\n",
    "        qty_left -= executable\n",
    "    return allocations\n",
    "\n",
    "def twap_strategy(df):\n",
    "    times = sorted(df['ts_event'].unique())\n",
    "    total_cost = 0\n",
    "    total_shares = 0\n",
    "    remaining_qty = ORDER_SIZE\n",
    "    bucket_size = ORDER_SIZE // len(times)\n",
    "\n",
    "    for ts in times:\n",
    "        if remaining_qty <= 0:\n",
    "            break\n",
    "        snapshot = df[df['ts_event'] == ts].set_index('publisher_id')\n",
    "        market_data = {\n",
    "            venue: {'ask_px': row['ask_px_00'], 'ask_sz': row['ask_sz_00']}\n",
    "            for venue, row in snapshot.iterrows()\n",
    "        }\n",
    "        allocations = best_ask_strategy(market_data, min(bucket_size, remaining_qty))\n",
    "        for venue, shares in allocations.items():\n",
    "            px = market_data[venue]['ask_px']\n",
    "            sz = market_data[venue]['ask_sz']\n",
    "            executed = min(shares, sz, remaining_qty)\n",
    "            if executed > 0:\n",
    "                total_cost += executed * px\n",
    "                total_shares += executed\n",
    "                remaining_qty -= executed\n",
    "\n",
    "    avg_price = total_cost / total_shares if total_shares > 0 else 0\n",
    "    return total_cost, avg_price\n",
    "\n",
    "def vwap_strategy(df):\n",
    "    total_volume = df['ask_sz_00'].sum()\n",
    "    total_cost = 0\n",
    "    total_shares = 0\n",
    "    remaining_qty = ORDER_SIZE\n",
    "\n",
    "    for ts in df['ts_event'].unique():\n",
    "        if remaining_qty <= 0:\n",
    "            break\n",
    "        snapshot = df[df['ts_event'] == ts].set_index('publisher_id')\n",
    "        vol = snapshot['ask_sz_00'].sum()\n",
    "        target = (vol / total_volume) * ORDER_SIZE\n",
    "        market_data = {\n",
    "            venue: {'ask_px': row['ask_px_00'], 'ask_sz': row['ask_sz_00']}\n",
    "            for venue, row in snapshot.iterrows()\n",
    "        }\n",
    "        allocations = best_ask_strategy(market_data, min(target, remaining_qty))\n",
    "        for venue, shares in allocations.items():\n",
    "            px = market_data[venue]['ask_px']\n",
    "            sz = market_data[venue]['ask_sz']\n",
    "            executed = min(shares, sz, remaining_qty)\n",
    "            if executed > 0:\n",
    "                total_cost += executed * px\n",
    "                total_shares += executed\n",
    "                remaining_qty -= executed\n",
    "\n",
    "    avg_price = total_cost / total_shares if total_shares > 0 else 0\n",
    "    return total_cost, avg_price\n",
