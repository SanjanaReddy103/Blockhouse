    "def main():\n",
    "    df = pd.read_csv('l1_day.csv')\n",
    "    df['ts_event'] = pd.to_datetime(df['ts_event'])\n",
    "    df = df.sort_values(['ts_event', 'publisher_id'])\n",
    "    df = df.groupby(['ts_event', 'publisher_id']).first().reset_index()\n",
    "\n",
    "    param_grid = list(product([0.1, 1, 10], repeat=3))\n",
    "    best_result = {'cost': float('inf'), 'params': None, 'avg_price': 0}\n",
    "\n",
    "    for lambda_over, lambda_under, theta_queue in param_grid:\n",
    "        cost, price = run_backtest(df, allocator, (lambda_over, lambda_under, theta_queue))\n",
    "        if price > 0 and cost < best_result['cost']:\n",
    "            best_result = {'cost': cost, 'params': {\n",
    "                'lambda_over': lambda_over,\n",
    "                'lambda_under': lambda_under,\n",
    "                'theta_queue': theta_queue\n",
    "            }, 'avg_price': price}\n",
    "\n",
    "    best_ask_cost, best_ask_price = run_backtest(df, best_ask_strategy)\n",
    "    twap_cost, twap_price = twap_strategy(df)\n",
    "    vwap_cost, vwap_price = vwap_strategy(df)\n",
    "\n",
    "    savings = {\n",
